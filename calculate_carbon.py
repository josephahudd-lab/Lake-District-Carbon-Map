#!/usr/bin/env python3
"""
calculate_carbon.py

Takes the gridded LiDAR stem-volume CSV generated by `carbon_lidar`,
spatially joins it with the Forestry Commission National Forest Inventory (NFI) mask,
applies species-specific biomass multipliers and carbon conversion factors,
and exports the result to CSV, GeoPackage (.gpkg), and GeoTIFF (.tif) raster.
"""

import os
import sys
import csv
import argparse
from typing import Dict, Optional

# Blended wood density / biomass multipliers from Forestry Commission / NFI categories
SPECIES_MULTIPLIERS = {
    'conifer': 0.475,
    'broadleaved': 0.812,
    'mixed mainly conifer': 0.576,
    'mixed mainly broadleaved': 0.711,
    'assumed woodland': 0.643,
    'low density': 0.643,
    'shrub': 0.300,
    'young trees': 0.200,
    'felled': 0.0,
    'windblow': 0.0,
    'ground prep': 0.0,
    'failed': 0.0,
}

CARBON_FRACTION = 0.50       # 50% carbon in dry woody biomass (IPCC standard)
CO2E_FACTOR = 44.0 / 12.0     # ~3.667 tCO2e per tonne of carbon

def get_multiplier(cat_string: Optional[str]) -> float:
    if not cat_string:
        return 0.0
    key = str(cat_string).strip().lower()
    return SPECIES_MULTIPLIERS.get(key, 0.0)

def process_with_geopandas(csv_path: str, nfi_path: str, out_prefix: str, cell_size: float = 20.0):
    import geopandas as gpd
    import pandas as pd
    from shapely.geometry import Point

    print(f"Reading volume CSV: {csv_path}")
    df = pd.read_csv(csv_path)
    if df.empty:
        print("Input CSV is empty!")
        return

    print(f"  Loaded {len(df):,} volume cells.")
    geometry = [Point(x, y) for x, y in zip(df['easting'], df['northing'])]
    gdf = gpd.GeoDataFrame(df, geometry=geometry, crs="EPSG:27700")

    print(f"Loading NFI woodland inventory: {nfi_path}")
    nfi_mask = gpd.read_file(nfi_path)
    if nfi_mask.crs != "EPSG:27700":
        print(f"  Reprojecting NFI from {nfi_mask.crs} to EPSG:27700...")
        nfi_mask = nfi_mask.to_crs("EPSG:27700")

    print("Executing spatial join (points in woodland polygons)...")
    joined = gpd.sjoin(gdf, nfi_mask, how="inner", predicate="intersects")
    print(f"  {len(joined):,} cells intersect with woodland.")

    type_col = 'IFT_IOA' if 'IFT_IOA' in joined.columns else ('CATEGORY' if 'CATEGORY' in joined.columns else None)
    if not type_col:
        print("Warning: Neither 'IFT_IOA' nor 'CATEGORY' found in NFI layer. Using default woodland multiplier 0.643.")
        joined['multiplier'] = 0.643
        joined['woodland_type'] = 'Woodland'
    else:
        joined['woodland_type'] = joined[type_col]
        joined['multiplier'] = joined[type_col].apply(get_multiplier)

    # Area factor: 20m x 20m = 400 m2 = 0.04 ha
    area_ha = (cell_size * cell_size) / 10000.0

    joined['biomass_tonnes'] = (joined['volume_ha'] * joined['multiplier'] * area_ha).round(3)
    joined['carbon_tonnes'] = (joined['biomass_tonnes'] * CARBON_FRACTION).round(3)
    joined['co2e_tonnes'] = (joined['carbon_tonnes'] * CO2E_FACTOR).round(3)
    joined['carbon_density_ha'] = (joined['volume_ha'] * joined['multiplier'] * CARBON_FRACTION).round(2)

    # Filter out zero-carbon cells
    filtered = joined[joined['carbon_tonnes'] > 0].copy()
    print(f"Final valid woodland carbon cells: {len(filtered):,}")

    out_csv = f"{out_prefix}_carbon.csv"
    out_gpkg = f"{out_prefix}_carbon.gpkg"

    cols = ['easting', 'northing', 'woodland_type', 'h90', 'volume_ha', 'biomass_tonnes', 'carbon_tonnes', 'co2e_tonnes', 'carbon_density_ha']
    filtered[cols].to_csv(out_csv, index=False)
    print(f"Exported CSV: {out_csv}")

    filtered[cols + ['geometry']].to_file(out_gpkg, driver="GPKG")
    print(f"Exported GeoPackage: {out_gpkg}")

    print_carbon_summary(filtered)

def process_with_gdal(csv_path: str, nfi_path: str, out_prefix: str, cell_size: float = 20.0, boundary_path: str = None):
    from osgeo import ogr, osr, gdal
    gdal.UseExceptions()

    print(f"Loading NFI vector layer: {nfi_path}")
    nfi_ds = ogr.Open(nfi_path)
    if not nfi_ds:
        raise RuntimeError(f"Could not open NFI file {nfi_path}")

    nfi_layer = nfi_ds.GetLayer(0)

    # Early National Park Boundary Filter Setup
    boundary_geom = None
    min_bx, max_bx, min_by, max_by = None, None, None, None
    if boundary_path and os.path.exists(boundary_path):
        print(f"Applying early Lake District National Park spatial filter: {boundary_path}")
        b_ds = ogr.Open(boundary_path)
        if b_ds:
            b_layer = b_ds.GetLayer()
            b_feat = b_layer.GetNextFeature()
            if b_feat:
                boundary_geom = b_feat.GetGeometryRef().Clone()
                b_srs = b_layer.GetSpatialRef()
                if b_srs and b_srs.IsGeographic():
                    tgt_b = osr.SpatialReference()
                    tgt_b.ImportFromEPSG(27700)
                    boundary_geom.Transform(osr.CoordinateTransformation(b_srs, tgt_b))
                # Set spatial filter on NFI layer so out-of-park polygons are never indexed!
                nfi_layer.SetSpatialFilter(boundary_geom)
                min_bx, max_bx, min_by, max_by = boundary_geom.GetEnvelope()
                print(f"  Boundary filter active. BNG Envelope: X=[{min_bx:.0f}, {max_bx:.0f}], Y=[{min_by:.0f}, {max_by:.0f}]")

    layer_defn = nfi_layer.GetLayerDefn()
    
    # Identify type field
    field_names = [layer_defn.GetFieldDefn(i).GetName() for i in range(layer_defn.GetFieldCount())]
    type_col = 'IFT_IOA' if 'IFT_IOA' in field_names else ('CATEGORY' if 'CATEGORY' in field_names else None)
    print(f"  Woodland classification field: {type_col}")

    # Build spatial index by loading geometries
    print("Reading NFI polygons...")
    from collections import defaultdict
    polygons = []
    spatial_grid = defaultdict(list)
    INDEX_BUCKET_SIZE = 1000.0  # 1km spatial buckets for ultra-fast point lookup

    for feat in nfi_layer:
        geom = feat.GetGeometryRef()
        if geom:
            woodland_type = feat.GetField(type_col) if type_col else "Woodland"
            env = geom.GetEnvelope()  # (minX, maxX, minY, maxY)
            entry = (env, geom.Clone(), woodland_type)
            polygons.append(entry)

            min_bx = int(env[0] // INDEX_BUCKET_SIZE)
            max_bx = int(env[1] // INDEX_BUCKET_SIZE)
            min_by = int(env[2] // INDEX_BUCKET_SIZE)
            max_by = int(env[3] // INDEX_BUCKET_SIZE)
            for bx in range(min_bx, max_bx + 1):
                for by in range(min_by, max_by + 1):
                    spatial_grid[(bx, by)].append(entry)

    print(f"  Loaded {len(polygons):,} woodland polygons indexed into {len(spatial_grid)} spatial buckets.")

    print(f"Processing points from {csv_path}...")
    area_ha = (cell_size * cell_size) / 10000.0

    out_csv = f"{out_prefix}_carbon.csv"
    out_gpkg = f"{out_prefix}_carbon.gpkg"

    # Setup output GeoPackage
    gpkg_driver = ogr.GetDriverByName("GPKG")
    if os.path.exists(out_gpkg):
        os.remove(out_gpkg)
    out_ds = gpkg_driver.CreateDataSource(out_gpkg)
    srs = osr.SpatialReference()
    srs.ImportFromEPSG(27700)
    out_layer = out_ds.CreateLayer("carbon_cells", srs, ogr.wkbPoint)

    for field_name, ftype in [
        ("woodland_type", ogr.OFTString),
        ("h90", ogr.OFTReal),
        ("volume_ha", ogr.OFTReal),
        ("biomass_tonnes", ogr.OFTReal),
        ("carbon_tonnes", ogr.OFTReal),
        ("co2e_tonnes", ogr.OFTReal),
        ("carbon_density_ha", ogr.OFTReal),
    ]:
        out_layer.CreateField(ogr.FieldDefn(field_name, ftype))

    matched_records = []
    TRANSACTION_BATCH_SIZE = 25000

    out_layer.StartTransaction()
    uncommitted = 0

    import time
    start_time = time.time()
    processed_count = 0

    with open(csv_path, 'r') as f, open(out_csv, 'w', newline='', buffering=65536) as out_f:
        reader = csv.DictReader(f)
        writer = csv.writer(out_f)
        writer.writerow(['easting', 'northing', 'woodland_type', 'h90', 'volume_ha', 'biomass_tonnes', 'carbon_tonnes', 'co2e_tonnes', 'carbon_density_ha'])

        layer_defn = out_layer.GetLayerDefn()

        for row in reader:
            processed_count += 1
            if processed_count % 500000 == 0:
                elapsed = time.time() - start_time
                rate = processed_count / elapsed if elapsed > 0 else 0
                print(f"  Processed {processed_count:,} cells ({rate:,.0f} cells/sec) - {len(matched_records):,} matched woodland cells...")

            east = float(row['easting'])
            north = float(row['northing'])

            # Fast early rejection: point completely outside National Park bounding box
            if boundary_geom is not None:
                if east < min_bx or east > max_bx or north < min_by or north > max_by:
                    continue

            bx = int(east // INDEX_BUCKET_SIZE)
            by = int(north // INDEX_BUCKET_SIZE)
            candidates = spatial_grid.get((bx, by))
            if not candidates:
                continue

            # Candidate envelope check first
            matched_type = None
            pt = None

            for env, poly_geom, w_type in candidates:
                if env[0] <= east <= env[1] and env[2] <= north <= env[3]:
                    if pt is None:
                        pt = ogr.Geometry(ogr.wkbPoint)
                        pt.AddPoint(east, north)
                    if poly_geom.Contains(pt):
                        matched_type = w_type
                        break

            if matched_type:
                # Precise statutory National Park boundary check
                if boundary_geom is not None:
                    if pt is None:
                        pt = ogr.Geometry(ogr.wkbPoint)
                        pt.AddPoint(east, north)
                    if not boundary_geom.Contains(pt):
                        continue

                mult = get_multiplier(matched_type)
                if mult <= 0.0:
                    continue

                h90 = float(row['h90'])
                # Biological ceiling check: reject extreme height artifacts (> 50m)
                if h90 > 50.0:
                    continue

                vol = float(row['volume_ha'])
                biomass = round(vol * mult * area_ha, 3)
                carbon = round(biomass * CARBON_FRACTION, 3)
                co2e = round(carbon * CO2E_FACTOR, 3)
                c_density = round(vol * mult * CARBON_FRACTION, 2)

                if carbon > 0:
                    writer.writerow([east, north, matched_type, h90, vol, biomass, carbon, co2e, c_density])

                    # Add to GPKG
                    if pt is None:
                        pt = ogr.Geometry(ogr.wkbPoint)
                        pt.AddPoint(east, north)
                    feat = ogr.Feature(layer_defn)
                    feat.SetField("woodland_type", str(matched_type))
                    feat.SetField("h90", h90)
                    feat.SetField("volume_ha", vol)
                    feat.SetField("biomass_tonnes", biomass)
                    feat.SetField("carbon_tonnes", carbon)
                    feat.SetField("co2e_tonnes", co2e)
                    feat.SetField("carbon_density_ha", c_density)
                    feat.SetGeometry(pt)
                    out_layer.CreateFeature(feat)
                    uncommitted += 1

                    if uncommitted >= TRANSACTION_BATCH_SIZE:
                        out_layer.CommitTransaction()
                        out_layer.StartTransaction()
                        uncommitted = 0

                    matched_records.append({
                        'carbon_tonnes': carbon,
                        'co2e_tonnes': co2e,
                        'biomass_tonnes': biomass,
                    })

    if uncommitted > 0:
        out_layer.CommitTransaction()

    out_ds = None
    elapsed_total = time.time() - start_time
    print(f"\nFinal valid woodland carbon cells: {len(matched_records):,} (completed in {elapsed_total:.2f}s)")
    print(f"Exported CSV: {out_csv}")
    print(f"Exported GeoPackage: {out_gpkg}")

    total_c = sum(r['carbon_tonnes'] for r in matched_records)
    total_co2e = sum(r['co2e_tonnes'] for r in matched_records)
    print("\n" + "=" * 50)
    print(" LAKE DISTRICT CARBON TOTALS")
    print("=" * 50)
    print(f" Total Stored Carbon   : {total_c:,.1f} tonnes C")
    print(f" Total CO2 Equivalent  : {total_co2e:,.1f} tonnes CO2e")
    print("=" * 50)

def print_carbon_summary(df):
    total_c = df['carbon_tonnes'].sum()
    total_co2e = df['co2e_tonnes'].sum()
    print("\n" + "=" * 50)
    print(" LAKE DISTRICT CARBON TOTALS")
    print("=" * 50)
    print(f" Total Stored Carbon   : {total_c:,.1f} tonnes C")
    print(f" Total CO2 Equivalent  : {total_co2e:,.1f} tonnes CO2e")
    print("=" * 50)

def generate_raster(gpkg_path: str, out_tif: str, cell_size: float = 20.0):
    import subprocess
    print(f"\nGenerating 20m GeoTIFF carbon density raster: {out_tif}")
    cmd = [
        "gdal_rasterize",
        "-a", "carbon_density_ha",
        "-tr", str(cell_size), str(cell_size),
        "-a_nodata", "0",
        "-ot", "Float32",
        "-co", "COMPRESS=DEFLATE",
        "-co", "PREDICTOR=2",
        "-co", "TILED=YES",
        gpkg_path,
        out_tif
    ]
    res = subprocess.run(cmd, capture_output=True, text=True)
    if res.returncode == 0:
        print(f"  Successfully created GeoTIFF: {out_tif}")
    else:
        print(f"  Rasterization notice: {res.stderr.strip() or res.stdout.strip()}")

def main():
    parser = argparse.ArgumentParser(description="Calculate biomass, carbon (tC), and CO2e from gridded volume and NFI mask")
    parser.add_argument("--csv", required=True, help="Gridded volume CSV from carbon_lidar")
    parser.add_argument("--nfi", required=True, help="Path to NFI GeoPackage / Shapefile")
    parser.add_argument("--output-prefix", default="lake_district", help="Output filename prefix")
    parser.add_argument("--grid-size", type=float, default=20.0, help="Grid size in metres (default: 20.0)")
    parser.add_argument("--raster", action="store_true", help="Generate a 20m GeoTIFF raster of carbon density (tC/ha)")
    
    default_b = os.path.join(os.path.dirname(os.path.abspath(__file__)), "docs", "lake_district_boundary.geojson")
    parser.add_argument("--boundary", default=default_b if os.path.exists(default_b) else None,
                        help="Path to National Park boundary GeoJSON to filter strictly to Lake District early")

    args = parser.parse_args()

    # Try GeoPandas first if installed, else fallback to GDAL/OGR
    try:
        import geopandas
        print("Using GeoPandas engine...")
        process_with_geopandas(args.csv, args.nfi, args.output_prefix, args.grid_size)
    except ImportError:
        print("GeoPandas not installed; using native GDAL/OGR C++ engine...")
        process_with_gdal(args.csv, args.nfi, args.output_prefix, args.grid_size, boundary_path=args.boundary)

    if args.raster:
        gpkg_path = f"{args.output_prefix}_carbon.gpkg"
        out_tif = f"{args.output_prefix}_carbon_20m.tif"
        if os.path.exists(gpkg_path):
            generate_raster(gpkg_path, out_tif, args.grid_size)

if __name__ == "__main__":
    main()
